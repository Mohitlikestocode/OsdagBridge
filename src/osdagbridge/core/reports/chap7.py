import logging

from osdagbridge.core.reports import styles
from osdagbridge.core.reports.charts import figure_tex, make_quantity_charts

logger = logging.getLogger(__name__)


def _quantity_charts_tex(input_dict, asset_dir):
    """LaTeX for the Chapter 7 quantity charts (empty when nothing to plot)."""
    if not asset_dir:
        return ""
    try:
        imgs = make_quantity_charts(input_dict, asset_dir)
    except Exception as exc:  # a chart problem must never break the report
        logger.warning("Quantity charts skipped: %s", exc)
        return ""
    if not imgs:
        return ""
    tex = ("\n\\vspace{1em}\n\\noindent\\textbf{Material Quantity Charts}\n\n"
           "\\noindent Charts summarising Table 7.1. Components whose quantity "
           "is not computed by the take-off are shown as n/a.\n\n")
    if "qty_steel" in imgs:
        tex += figure_tex(imgs["qty_steel"], "Structural steel tonnage by component", "fig:qty-steel",
                          width=styles.CHART_FIGURE_WIDTH_SMALL)
    if "qty_concrete_rebar" in imgs:
        tex += figure_tex(imgs["qty_concrete_rebar"],
                          "Concrete volume (m$^3$) and reinforcement steel weight (MT) of the deck slab",
                          "fig:qty-concrete-rebar", width=styles.CHART_FIGURE_WIDTH_SMALL)
    return tex


